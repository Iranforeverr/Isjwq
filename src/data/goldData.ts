// Helper to format numbers with separators
export function formatPrice(val: number, isUSD = false): string {
  if (isUSD) {
    return '$' + val.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
  }
  return val.toLocaleString('fa-IR') + ' تومان';
}

export function formatPriceCompact(val: number, isUSD = false): string {
  if (isUSD) {
    return '$' + val.toLocaleString('en-US', { maximumFractionDigits: 1 });
  }
  if (val >= 1000000) {
    const million = val / 1000000;
    return million.toLocaleString('fa-IR', { maximumFractionDigits: 2 }) + ' میلیون تومان';
  }
  return val.toLocaleString('fa-IR') + ' تومان';
}
